// Package mtproxy integrates telemt (Rust MTProxy) into the gateway:
//   - detects MTProxy FakeTLS ClientHello messages (HMAC of client_random with a user secret),
//   - forwards matching connections to the local telemt instance with a PROXY v2 header,
//   - generates telemt's config.toml from our settings and prints tg:// links.
package mtproxy

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"fmt"
	"log/slog"
	"net"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"securegate/internal/netx"
)

type Forwarder struct {
	secrets  map[string][]byte
	upstream string
}

func NewForwarder(secrets map[string][]byte, internalPort int) *Forwarder {
	return &Forwarder{secrets: secrets, upstream: fmt.Sprintf("127.0.0.1:%d", internalPort)}
}

// Match checks whether the TLS record (5-byte header + ClientHello) was produced by a Telegram
// client using one of our secrets. Returns the user name.
//
// FakeTLS: client_random (32 bytes at offset 11) = HMAC-SHA256(secret, record with zeroed random)
// XOR (28 zero bytes || little-endian uint32 unix time).
func (f *Forwarder) Match(record []byte) (string, bool) {
	if f == nil || len(f.secrets) == 0 || len(record) < 11+32 {
		return "", false
	}
	random := record[11:43]
	zeroed := make([]byte, len(record))
	copy(zeroed, record)
	for i := 11; i < 43; i++ {
		zeroed[i] = 0
	}
	for name, sec := range f.secrets {
		m := hmac.New(sha256.New, sec)
		m.Write(zeroed)
		d := m.Sum(nil)
		ok := true
		for i := 0; i < 28; i++ {
			if d[i] != random[i] {
				ok = false
				break
			}
		}
		if !ok {
			continue
		}
		var tsb [4]byte
		for i := 0; i < 4; i++ {
			tsb[i] = d[28+i] ^ random[28+i]
		}
		ts := int64(binary.LittleEndian.Uint32(tsb[:]))
		if skew := time.Now().Unix() - ts; skew > 86400 || skew < -86400 {
			slog.Debug("mtproxy: FakeTLS timestamp skew is large (telemt will decide)", "user", name, "skew_s", skew)
		}
		return name, true
	}
	return "", false
}

// Forward relays the client connection to telemt. first holds bytes already read from client.
func (f *Forwarder) Forward(c net.Conn, first []byte) {
	up, err := net.DialTimeout("tcp", f.upstream, 5*time.Second)
	if err != nil {
		slog.Error("mtproxy: telemt is not reachable", "addr", f.upstream, "err", err)
		c.Close()
		return
	}
	hdr := netx.ProxyV2Header(c.RemoteAddr(), c.LocalAddr())
	if _, err := up.Write(append(hdr, first...)); err != nil {
		up.Close()
		c.Close()
		return
	}
	netx.Pipe(c, up)
}

// Links returns tg:// links for all users.
func Links(domain string, port int, users map[string]string) map[string]string {
	out := map[string]string{}
	for name, sec := range users {
		full := "ee" + strings.ToLower(sec) + hex.EncodeToString([]byte(domain))
		q := url.Values{}
		q.Set("server", domain)
		q.Set("port", fmt.Sprint(port))
		q.Set("secret", full)
		out[name] = "tg://proxy?" + q.Encode()
	}
	return out
}

// WriteDisabled tells the telemt container to stay idle (reason is printed in its log).
func WriteDisabled(dir, reason string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	_ = os.Remove(filepath.Join(dir, "config.toml"))
	return os.WriteFile(filepath.Join(dir, "DISABLED"), []byte(reason+"\n"), 0o644)
}

var ifaceNameRe = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,15}$`)

// WriteTelemtConfig writes telemt's config.toml (telemt watches and hot-reloads it).
//
// upstreamIface (optional): telemt's outgoing connections to Telegram (DCs / middle proxies) are
// bound to the address of this interface - the WireGuard uplink to the main server on a proxy-only
// install (wireguard container, WG_MODE=uplink, which routes that source address into the tunnel).
// Fail-closed: without the interface/address telemt cannot connect at all, nothing leaks directly.
func WriteTelemtConfig(dir string, enabled bool, domain string, publicPort, internalPort, maskPort int, adTag, upstreamIface string, users map[string]string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	marker := filepath.Join(dir, "DISABLED")
	if !enabled || len(users) == 0 {
		_ = os.WriteFile(marker, []byte("MTProxy disabled (MTPROXY_ENABLE=false or no users)\n"), 0o644)
		return nil
	}
	if upstreamIface != "" && !ifaceNameRe.MatchString(upstreamIface) {
		_ = os.Remove(filepath.Join(dir, "config.toml"))
		_ = os.WriteFile(marker, []byte("MTProxy disabled: invalid MTPROXY_UPSTREAM_IFACE\n"), 0o644)
		return fmt.Errorf("MTPROXY_UPSTREAM_IFACE=%q is not a valid interface name", upstreamIface)
	}
	_ = os.Remove(marker)
	names := make([]string, 0, len(users))
	for k := range users {
		names = append(names, k)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("# GENERATED by securegate gateway from .env / config/users.yml - do not edit\n")
	// Middle proxy (ME) is only required for the sponsored-channel ad_tag. Without it, direct
	// connections to Telegram DCs are simpler and do not depend on detecting the server's
	// public IP behind NAT (ME key derivation).
	fmt.Fprintf(&b, "[general]\nuse_middle_proxy = %t\nlog_level = \"normal\"\n", adTag != "")
	if adTag != "" {
		fmt.Fprintf(&b, "ad_tag = %q\n", adTag)
	}
	b.WriteString("\n[general.modes]\nclassic = false\nsecure = false\ntls = true\n")
	fmt.Fprintf(&b, "\n[general.links]\nshow = \"*\"\npublic_host = %q\npublic_port = %d\n", domain, publicPort)
	fmt.Fprintf(&b, "\n[server]\nport = %d\nproxy_protocol = true\n", internalPort)
	b.WriteString("\n[server.api]\nenabled = true\nlisten = \"127.0.0.1:9091\"\nwhitelist = [\"127.0.0.1/32\"]\n")
	b.WriteString("\n[[server.listeners]]\nip = \"127.0.0.1\"\n")
	fmt.Fprintf(&b, "\n[censorship]\ntls_domain = %q\nmask = true\nmask_host = \"127.0.0.1\"\nmask_port = %d\ntls_emulation = true\ntls_front_dir = \"tlsfront\"\n", domain, maskPort)
	// The gateway forwards a connection to telemt only after the FakeTLS HMAC of a user secret
	// matched, so the client is already authenticated. The SNI inside the client's ee-secret
	// may legitimately differ from DOMAIN (link built for another/fronting domain, old link
	// after a DOMAIN change, subdomain vs apex): telemt's default "drop" made Telegram show the
	// proxy as unavailable ("TLS handshake rejected by unknown SNI policy"). Accept any SNI.
	b.WriteString("unknown_sni_action = \"accept\"\n")
	if upstreamIface != "" {
		// Outgoing connections are bound to the uplink interface's address; the wireguard container
		// routes that source address into the tunnel (policy rule). IPv4 only (the tunnel carries
		// IPv4). The TLS-front fetch from mask_host (127.0.0.1) also goes through the upstream: a local
		// source address still reaches loopback, so tls_emulation keeps working.
		fmt.Fprintf(&b, "\n[[upstreams]]\ntype = \"direct\"\ninterface = %q\nipv4 = true\nipv6 = false\n", upstreamIface)
	}
	b.WriteString("\n[access.users]\n")
	for _, n := range names {
		fmt.Fprintf(&b, "%q = %q\n", n, strings.ToLower(users[n]))
	}
	path := filepath.Join(dir, "config.toml")
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
