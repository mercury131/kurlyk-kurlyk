package mtproxy

// Alternative MTProxy implementations, each on its own public port, with the SAME users as telemt
// (MTPROXY_USERS / config/users.yml -> mtproxy_users, set once):
//
//	mtprotoproxy (Python, github.com/alexbers/mtprotoproxy)  -> data/mtproxy/mtprotoproxy/config.py
//	teleproxy    (C, github.com/teleproxy/teleproxy)         -> data/mtproxy/teleproxy/args
//
// Like telemt they listen on 127.0.0.1 only and expect a PROXY v2 header: the gateway accepts the
// public port with the same detector as :443 (MTProxy HMAC check, guard, website for everyone
// else) and forwards only authenticated Telegram clients. Each container restarts its proxy
// when the generated file changes; a DISABLED marker keeps it idle.

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

func sortedNames(users map[string]string) []string {
	names := make([]string, 0, len(users))
	for k := range users {
		names = append(names, k)
	}
	sort.Strings(names)
	return names
}

func writeAtomic(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// writeAltCommon prepares dir, handles the DISABLED marker. Returns false if disabled.
func writeAltCommon(dir string, enabled bool, users map[string]string, cfgFile string) (bool, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return false, err
	}
	marker := filepath.Join(dir, "DISABLED")
	if !enabled || len(users) == 0 {
		_ = os.Remove(filepath.Join(dir, cfgFile))
		return false, os.WriteFile(marker, []byte("disabled (port 0, *_ENABLE=false or no MTProxy users)\n"), 0o644)
	}
	_ = os.Remove(marker)
	return true, nil
}

// WriteMTProtoProxyConfig writes config.py for alexbers/mtprotoproxy.
// maskPort: the gateway's HTTPS port on 127.0.0.1 - mtprotoproxy reads the length of the real
// certificate from it (fake-TLS emulation) and would mask bad clients to it.
func WriteMTProtoProxyConfig(dir string, enabled bool, domain string, internalPort, maskPort int, adTag string, users map[string]string) error {
	ok, err := writeAltCommon(dir, enabled, users, "config.py")
	if !ok || err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# GENERATED by securegate gateway from .env / config/users.yml - do not edit\n")
	fmt.Fprintf(&b, "PORT = %d\n", internalPort)
	b.WriteString("LISTEN_ADDR_IPV4 = \"127.0.0.1\"\nLISTEN_ADDR_IPV6 = \"\"\n")
	b.WriteString("PROXY_PROTOCOL = True\n")
	b.WriteString("MODES = {\"classic\": False, \"secure\": False, \"tls\": True}\n")
	fmt.Fprintf(&b, "TLS_DOMAIN = %q\n", domain)
	fmt.Fprintf(&b, "MASK = True\nMASK_HOST = \"127.0.0.1\"\nMASK_PORT = %d\n", maskPort)
	// prefer IPv4 to Telegram DCs: many servers have no working IPv6 route
	b.WriteString("PREFER_IPV6 = False\n")
	if adTag != "" {
		fmt.Fprintf(&b, "AD_TAG = %q\n", strings.ToLower(adTag))
	}
	b.WriteString("USERS = {\n")
	for _, n := range sortedNames(users) {
		fmt.Fprintf(&b, "    %q: %q,\n", n, strings.ToLower(users[n]))
	}
	b.WriteString("}\n")
	return writeAtomic(filepath.Join(dir, "config.py"), []byte(b.String()))
}

var tpLabelBad = regexp.MustCompile(`[^A-Za-z0-9_-]`)

// WriteTeleproxyArgs writes the teleproxy command line (one argument per line).
// hosts: every domain a client link may contain (fake-TLS SNI). teleproxy takes the TLS
// fingerprint of each domain from <domain>:maskPort; the container maps these names to 127.0.0.1
// in its /etc/hosts (file "hosts"), so that is the gateway's own TLS with the real certificate.
func WriteTeleproxyArgs(dir string, enabled bool, hosts []string, internalPort, maskPort int, adTag string, users map[string]string) error {
	ok, err := writeAltCommon(dir, enabled, users, "args")
	if !ok || err != nil {
		return err
	}
	args := []string{
		"-u", "nobody",
		"--address", "127.0.0.1",
		"-H", fmt.Sprint(internalPort),
		"-p", fmt.Sprint(internalPort + 1000), // local stats port (no --http-stats: not served)
		"--proxy-protocol",
	}
	if adTag != "" {
		// sponsored channel needs the middle proxies (the entrypoint downloads their config)
		args = append(args, "-P", strings.ToLower(adTag), "--aes-pwd", "/etc/teleproxy/proxy-secret")
	} else {
		args = append(args, "--direct")
	}
	for _, h := range hosts {
		if maskPort == 443 {
			args = append(args, "-D", h)
		} else {
			args = append(args, "-D", fmt.Sprintf("%s:%d", h, maskPort))
		}
	}
	if err := writeAtomic(filepath.Join(dir, "hosts"), []byte(strings.Join(hosts, "\n")+"\n")); err != nil {
		return err
	}
	for _, n := range sortedNames(users) {
		label := tpLabelBad.ReplaceAllString(n, "_")
		if len(label) > 32 {
			label = label[:32]
		}
		args = append(args, "-S", strings.ToLower(users[n])+":"+label)
	}
	if adTag != "" {
		args = append(args, "/etc/teleproxy/proxy-multi.conf")
	}
	return writeAtomic(filepath.Join(dir, "args"), []byte(strings.Join(args, "\n")+"\n"))
}
